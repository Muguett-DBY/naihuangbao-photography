const copies = { en, "zh-CN": zh, ja, ko } as const;

function resolveLanguage(language: string): keyof typeof copies {
  if (language.startsWith("zh")) return "zh-CN";
  if (language.startsWith("ja")) return "ja";
  if (language.startsWith("ko")) return "ko";
  return "en";
}

export function useWorkspaceCopy() {
  const { i18n } = useTranslation();
  const language = resolveLanguage(i18n.resolvedLanguage ?? i18n.language);
  const copy = copies[language];
  const text = useCallback((key: WorkspaceCopyKey, values: Record<string, string | number> = {}) => {
    return Object.entries(values).reduce(
      (value, [name, replacement]) => value.replaceAll(`{{${name}}}`, String(replacement)),
      copy[key],
    );
  }, [copy]);
  const locale = language === "zh-CN" ? "zh-CN" : language === "ja" ? "ja-JP" : language === "ko" ? "ko-KR" : "en-US";
  return { text, locale };
}
